def get_ase_bam_path(haplotype, celltype):
    """
    Get path to the .ase.bam file for a given haplotype and cell type.

    Args:
      haplotype: 'hap1' or 'hap2'
      celltype:  'iPSC', 'FPP', 'astrocyte', or 'microglia'

    Returns: full path to .ase.bam file
    """
    return os.path.join(ASE_DIR,
        f't2t_h9_v01_{haplotype}.H9-02-ES-001_{celltype}.ase.bam')


def count_reads_at_position(bam_path, chrom, pos):
    """
    Count reads overlapping a single position in a BAM file.
    Uses samtools view -c.

    Returns: int (read count)
    """
    region = f"{chrom}:{pos}-{pos}"
    try:
        result = subprocess.run(
            [SAMTOOLS, 'view', '-c', bam_path, region],
            capture_output=True, text=True, timeout=10
        )
        return int(result.stdout.strip()) if result.returncode == 0 else 0
    except Exception:
        return 0


def count_ase_reads(gene, hap1_abs, hap2_abs, celltype):
    """
    Count allele-specific reads at a variant position for one cell type.

    Args:
      gene:     gene name
      hap1_abs: absolute hap1 coordinate
      hap2_abs: absolute hap2 coordinate
      celltype: cell type name

    Returns: (hap1_reads, hap2_reads)
    """
    cfg = GENES_CONFIG[gene]
    h1_bam = get_ase_bam_path('hap1', celltype)
    h2_bam = get_ase_bam_path('hap2', celltype)
    h1_reads = count_reads_at_position(h1_bam, cfg['hap1_chrom'], hap1_abs)
    h2_reads = count_reads_at_position(h2_bam, cfg['hap2_chrom'], hap2_abs)
    return h1_reads, h2_reads


def count_ase_all_celltypes(gene, hap1_abs, hap2_abs):
    """
    Count ASE reads across all 4 cell types.

    Returns: dict {celltype: (hap1_reads, hap2_reads)}
    """
    return {ct: count_ase_reads(gene, hap1_abs, hap2_abs, ct) for ct in CELLTYPES}


def count_gene_level_ase(gene, celltype):
    """
    Count total gene-level ASE reads (as done in Figure 3).
    Uses `samtools view -c` on the entire gene body region.

    Returns: (hap1_total, hap2_total)
    """
    cfg = GENES_CONFIG[gene]
    gb_h1 = cfg['gene_body_hap1']
    gb_h2 = cfg['gene_body_hap2']

    h1_bam = get_ase_bam_path('hap1', celltype)
    h2_bam = get_ase_bam_path('hap2', celltype)

    h1_region = f"{cfg['hap1_chrom']}:{gb_h1[0]}-{gb_h1[1]}"
    h2_region = f"{cfg['hap2_chrom']}:{gb_h2[0]}-{gb_h2[1]}"

    try:
        r1 = subprocess.run([SAMTOOLS, 'view', '-c', h1_bam, h1_region],
                            capture_output=True, text=True, timeout=10)
        h1 = int(r1.stdout.strip()) if r1.returncode == 0 else 0
    except Exception:
        h1 = 0

    try:
        r2 = subprocess.run([SAMTOOLS, 'view', '-c', h2_bam, h2_region],
                            capture_output=True, text=True, timeout=10)
        h2 = int(r2.stdout.strip()) if r2.returncode == 0 else 0
    except Exception:
        h2 = 0

    return h1, h2


