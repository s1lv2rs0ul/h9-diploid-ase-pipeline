# 4. SEQUENCE EXTRACTION (for Evo2)
# ════════════════════════════════════════════════════════════════════════════

def fetch_haplotype_sequence(haplotype, chrom, start, end):
    """
    Fetch sequence from a haplotype reference FASTA.

    Args:
      haplotype: 'hap1' or 'hap2'
      chrom: chromosome name (e.g., 'chr4_hap1')
      start, end: 1-based coordinates

    Returns: uppercase DNA sequence string
    """
    ref_fa = HAP1_REF if haplotype == 'hap1' else HAP2_REF
    region = f"{chrom}:{start}-{end}"
    try:
        result = subprocess.run(
            [SAMTOOLS, 'faidx', ref_fa, region],
            capture_output=True, text=True, timeout=10
        )
        if result.returncode != 0:
            return ''
        return ''.join(result.stdout.strip().split('\n')[1:]).upper()
    except Exception:
        return ''


def fetch_hg38_sequence(chrom, start, end):
    """Fetch sequence from hg38 reference."""
    region = f"{chrom}:{start}-{end}"
    try:
        result = subprocess.run(
            [SAMTOOLS, 'faidx', HG38_REF, region],
            capture_output=True, text=True, timeout=10
        )
        if result.returncode != 0:
            return ''
        return ''.join(result.stdout.strip().split('\n')[1:]).upper()
    except Exception:
        return ''


def make_evo2_sequences(gene, hap1_abs, hap1_base, hap2_base, variant_type,
                        flank=FLANK):
    """
    Extract ref and alt sequences for Evo2 scoring.

    For SNVs: extracts ±flank bp around the variant from hap1 reference,
    then substitutes the alt (hap2) base at center.

    Args:
      gene:         gene name
      hap1_abs:     absolute hap1 coordinate
      hap1_base:    reference allele (hap1)
      hap2_base:    alternate allele (hap2)
      variant_type: 'SNV', 'INS(Nbp)', 'DEL(Nbp)', etc.
      flank:        flanking bp (default 512)

    Returns: (ref_seq, alt_seq) — each ~1024 bp
    """
    if variant_type != 'SNV' or len(hap1_base) != 1 or len(hap2_base) != 1:
        return '', ''

    cfg = GENES_CONFIG[gene]
    h1_chrom = cfg['hap1_chrom']

    ref_seq = fetch_haplotype_sequence(
        'hap1', h1_chrom,
        max(1, hap1_abs - flank),
        hap1_abs + flank
    )
    if not ref_seq:
        return '', ''

    # Alt sequence: substitute variant base at center position
    offset = flank  # variant is at center
    alt_seq = ref_seq[:offset] + hap2_base.upper() + ref_seq[offset + 1:]

    return ref_seq, alt_seq


