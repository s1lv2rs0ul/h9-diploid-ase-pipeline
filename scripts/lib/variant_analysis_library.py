def rel_to_abs(gene, hap1_pos_rel, hap2_pos_rel):
    """
    Convert relative FASTA positions to absolute haplotype coordinates.

    Args:
      gene: gene name (SNCA, HTT, LRRK2, GBA, SMN1)
      hap1_pos_rel: position within extracted hap1 FASTA (from CSV)
      hap2_pos_rel: position within extracted hap2 FASTA (from CSV)

    Returns:
      (hap1_abs, hap2_abs) — absolute coordinates for use with .ase.bam

    Formula: abs = fasta_start + rel_pos
    Where fasta_start = gene_TSS - 500000
    """
    cfg = GENES_CONFIG[gene]
    h1_abs = cfg['fasta_start_hap1'] + hap1_pos_rel
    h2_abs = cfg['fasta_start_hap2'] + hap2_pos_rel
    return h1_abs, h2_abs


def is_in_gene_body(gene, hap1_abs, hap2_abs):
    """
    Check if a variant falls within the gene body on either haplotype.

    Uses gene body coordinates from CAT GTF annotations.
    """
    cfg = GENES_CONFIG[gene]
    gb_h1 = cfg['gene_body_hap1']
    gb_h2 = cfg['gene_body_hap2']
    return (gb_h1[0] <= hap1_abs <= gb_h1[1]) or \
           (gb_h2[0] <= hap2_abs <= gb_h2[1])


def variant_distance_to_tss(gene, hap1_rel):
    """
    Return distance from variant to gene TSS.
    Negative = upstream, positive = downstream (within gene body).

    The hap1_rel column in variant CSVs is already this value.
    """
    return hap1_rel


