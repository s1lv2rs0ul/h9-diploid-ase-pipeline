def load_catalog(path=None):
    """
    Load the full variant catalog CSV.

    Default path: ase_v2/all_variants_astrocyte_ase_evo2.csv
    """
    if path is None:
        path = os.path.join(ASE_V2, 'all_variants_astrocyte_ase_evo2.csv')

    rows = []
    with open(path) as f:
        reader = csv.DictReader(f)
        for row in reader:
            # Convert numeric fields
            for key in ['hap1_abs_pos', 'hap2_abs_pos', 'hap1_rel_to_tss',
                        'astro_hap1_reads', 'astro_hap2_reads',
                        'iPSC_hap1_reads', 'iPSC_hap2_reads',
                        'FPP_hap1_reads', 'FPP_hap2_reads',
                        'micro_hap1_reads', 'micro_hap2_reads']:
                if key in row and row[key]:
                    row[key] = int(row[key])
            rows.append(row)
    return rows


