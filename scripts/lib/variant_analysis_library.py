def load_variants(gene):
    """
    Load variants from the correct haplotype-aligned CSV for a given gene.

    Returns list of dicts with keys:
      hap1_pos_rel, hap2_pos_rel, hap1_rel (relative to TSS),
      hap1_base, hap2_base, type

    Example:
      >>> variants = load_variants('SNCA')
      >>> len(variants)
      832
    """
    if gene not in GENES_CONFIG:
        raise ValueError(f"Unknown gene: {gene}. Available: {list(GENES_CONFIG.keys())}")

    cfg = GENES_CONFIG[gene]
    path = cfg['variant_file']
    variants = []

    with open(path) as f:
        reader = csv.DictReader(f)
        for row in reader:
            # Filter by gene column if shared CSV (HTT/LRRK2/GBA)
            if cfg.get('has_gene_col') and row.get('gene') != cfg.get('gene_filter'):
                continue
            variants.append({
                'hap1_pos_rel': int(row['hap1_pos']),
                'hap2_pos_rel': int(row['hap2_pos']),
                'hap1_rel':     int(row['hap1_rel']),
                'hap1_base':    row['hap1_base'],
                'hap2_base':    row['hap2_base'],
                'type':         row['type'],
            })
    return variants


def load_all_variants():
    """Load variants for all genes. Returns dict: {gene: [variants]}."""
    return {gene: load_variants(gene) for gene in GENES_CONFIG}


