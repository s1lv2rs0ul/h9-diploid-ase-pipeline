# 5. GENE-LEVEL SUMMARY & VERIFICATION
# ════════════════════════════════════════════════════════════════════════════

def summarize_gene(gene, variants=None):
    """
    Print summary stats for a gene: variant counts, types, gene body overlap.

    Args:
      gene: gene name
      variants: optional pre-loaded variant list (loads if None)
    """
    if variants is None:
        variants = load_variants(gene)

    cfg = GENES_CONFIG[gene]
    snvs = [v for v in variants if v['type'] == 'SNV']
    indels = [v for v in variants if v['type'] != 'SNV']

    # Count in gene body
    in_body = 0
    for v in variants:
        h1_abs, h2_abs = rel_to_abs(gene, v['hap1_pos_rel'], v['hap2_pos_rel'])
        if is_in_gene_body(gene, h1_abs, h2_abs):
            in_body += 1

    print(f"{gene}:")
    print(f"  Total variants:  {len(variants)} (expected {cfg['expected_variants']})")
    print(f"  SNVs:            {len(snvs)}")
    print(f"  Indels:          {len(indels)}")
    print(f"  In gene body:    {in_body}")


def verify_gene_level_ase(gene, celltype='astrocyte'):
    """
    Verify gene-level ASE counts match the figure's published values.

    Returns: (computed_h1, computed_h2, figure_h1, figure_h2, match)
    """
    h1, h2 = count_gene_level_ase(gene, celltype)
    fig_h1, fig_h2 = FIGURE_ASE_COUNTS[gene][celltype]
    match = (h1 == fig_h1 and h2 == fig_h2)
    print(f"{gene} {celltype}: computed H1={h1} H2={h2} | "
          f"figure H1={fig_h1} H2={fig_h2} | "
          f"{'MATCH' if match else 'MISMATCH'}")
    return h1, h2, fig_h1, fig_h2, match


