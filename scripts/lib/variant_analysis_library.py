# 6. FILTERING & SUBSETTING
# ════════════════════════════════════════════════════════════════════════════

def filter_snvs(variants):
    """Return only SNV variants."""
    return [v for v in variants if v['type'] == 'SNV']


def filter_gene_body(gene, variants):
    """Return only variants within the gene body."""
    return [
        v for v in variants
        if is_in_gene_body(gene, *rel_to_abs(gene, v['hap1_pos_rel'], v['hap2_pos_rel']))
    ]


def filter_by_region(gene, variants, upstream_bp=0, downstream_bp=0):
    """
    Filter variants by distance to TSS.

    Args:
      upstream_bp:   include variants up to N bp upstream of TSS (negative hap1_rel)
      downstream_bp: include variants up to N bp downstream of TSS (positive hap1_rel)

    Example: filter_by_region('SNCA', variants, upstream_bp=5000, downstream_bp=0)
             → variants within 5kb upstream of SNCA TSS
    """
    return [
        v for v in variants
        if -upstream_bp <= v['hap1_rel'] <= downstream_bp
    ]


def filter_with_ase_reads(gene, variants, celltype='astrocyte', min_reads=1):
    """
    Filter to variants that have at least min_reads total ASE reads.
    WARNING: This calls samtools for each variant — can be slow.
    """
    result = []
    for v in variants:
        h1_abs, h2_abs = rel_to_abs(gene, v['hap1_pos_rel'], v['hap2_pos_rel'])
        h1r, h2r = count_ase_reads(gene, h1_abs, h2_abs, celltype)
        if h1r + h2r >= min_reads:
            v_copy = dict(v)
            v_copy['hap1_reads'] = h1r
            v_copy['hap2_reads'] = h2r
            result.append(v_copy)
    return result


